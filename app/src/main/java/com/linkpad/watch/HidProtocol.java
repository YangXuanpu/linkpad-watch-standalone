    public static byte[] mouseReport(int buttons,int dx,int dy,int wheel,int pan) {
        return new byte[]{(byte)(buttons&31),(byte)clamp(dx),(byte)clamp(dy),(byte)clamp(wheel),(byte)clamp(pan)};
    }
    public static byte[] keyboardReport(int modifiers,int key) {
        byte[] r=new byte[8]; r[0]=(byte)modifiers; r[2]=(byte)key; return r;
    }
    private static int clamp(int v){return Math.max(-127,Math.min(127,v));}
